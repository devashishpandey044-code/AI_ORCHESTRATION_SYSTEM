"""Run every eval and write one report with the real numbers.

    python -m app.evals.report            print the report
    python -m app.evals.report --write    write docs/eval-report.md
    python -m app.evals.report --check    fail if docs/eval-report.md is out of date

The report holds no dates and no timings, so it only changes when a result changes. The check
mode is what stops the committed report from drifting away from the code.
"""

import contextlib
import importlib
import io
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

REPORT_PATH = Path(__file__).resolve().parents[2] / "docs" / "eval-report.md"

# (title, module, what it checks). Order is the order in the report.
EVALS = (
    (
        "Grounding",
        "app.evals.grounding",
        "Quotes the model gives must really be in the user's words.",
    ),
    ("Safety", "app.evals.safety", "Crisis language stops everything and the model is not called."),
    ("Retrieval", "app.evals.retrieval", "A question finds the right method in the library."),
    ("Roadblocks", "app.evals.roadblocks", "Rules turn activity data into the right roadblocks."),
    (
        "Pipeline",
        "app.evals.pipeline",
        "Words and data to roadblocks to methods, plus rules that hold for every combination.",
    ),
    ("Planning", "app.evals.planning", "Every schedule passes an independent validator."),
    (
        "Personas",
        "app.evals.personas",
        "Made-up users through detection, planning and check-ins together.",
    ),
    (
        "Check-ins",
        "app.evals.checkins",
        "Plan against reality: adherence, patterns, weekly review.",
    ),
)

NOT_PROVEN = (
    "The model is scripted in every eval, so these check what the code does with a model answer, "
    "not how good a real model's answers are.",
    "Labels and personas are written by hand, so they encode the author's own judgement.",
    "Thresholds (for example the 60/85/125/30 percent check-in cut-offs) are first guesses "
    "that have not been tuned on real users.",
    "Nothing here measures whether the advice helps a real person.",
)


@dataclass(frozen=True)
class EvalRun:
    title: str
    purpose: str
    passed: bool
    lines: tuple[str, ...]


def run_eval(title: str, purpose: str, main: Callable[[], int]) -> EvalRun:
    """Run one eval's main(), capture what it prints, and never let a crash hide."""
    buffer = io.StringIO()
    try:
        with contextlib.redirect_stdout(buffer):
            code = main()
        passed = code == 0
        text = buffer.getvalue()
    except Exception as error:  # a crashing eval is a failing eval
        passed = False
        text = buffer.getvalue() + f"CRASH: {error!r}\n"
    lines = tuple(line.rstrip() for line in text.splitlines() if line.strip())
    return EvalRun(title, purpose, passed, lines)


def run_all() -> list[EvalRun]:
    runs = []
    for title, module, purpose in EVALS:
        runs.append(run_eval(title, purpose, importlib.import_module(module).main))
    return runs


def render(runs: list[EvalRun]) -> str:
    passed = sum(1 for run in runs if run.passed)
    out = [
        "# Evaluation report",
        "",
        "Generated by `python -m app.evals.report --write`. Do not edit by hand: "
        "`scripts/check.sh` fails when this file is out of date.",
        "",
        f"**{passed} of {len(runs)} evals pass.** Each one is a gate in CI.",
        "",
        "| Eval | What it checks | Result |",
        "| --- | --- | --- |",
    ]
    for run in runs:
        out.append(f"| {run.title} | {run.purpose} | {'PASS' if run.passed else 'FAIL'} |")
    out.append("")
    for run in runs:
        out.extend([f"## {run.title}", "", run.purpose, "", "```text", *run.lines, "```", ""])
    out.extend(["## What this does not prove", ""])
    out.extend(f"- {item}" for item in NOT_PROVEN)
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None, path: Path = REPORT_PATH) -> int:
    args = sys.argv[1:] if argv is None else argv
    runs = run_all()
    text = render(runs)
    all_pass = all(run.passed for run in runs)
    if "--write" in args:
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.name}: {sum(r.passed for r in runs)}/{len(runs)} evals pass")
        return 0 if all_pass else 1
    if "--check" in args:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            print(f"{path.name} is out of date. Run: python -m app.evals.report --write")
            return 1
        print(f"{path.name} is up to date")
        return 0 if all_pass else 1
    print(text)
    return 0 if all_pass else 1


if __name__ == "__main__":
    raise SystemExit(main())
